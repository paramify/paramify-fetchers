#!/usr/bin/env python3
"""Regenerate mappings/solution_capabilities.yaml from the mapping sheet.

Input is a CSV export of the sheet's "20x Mapping" tab — one row per
(capability, KSI, fetcher), with at least the columns `Sol Cap ID`, `Sol Cap`,
`KSI` and `Fetcher Name` (`Platform` is read when present, for a check). Rows
collapse to one entry per (fetcher, capability), the KSIs gathered onto it.
Rows with no fetcher are skipped: they record a capability nothing covers yet,
which is the sheet's business, not the pairing's. Rows naming a fetcher this
repo does not have are skipped too, and reported.

The output is deterministic (sorted, no timestamps beyond `imported_at`), so a
scheduled re-import only produces a diff when the sheet actually changed.

Every run also checks the rows and reports what looks wrong in the sheet: an
id that is not a library id, one id under two names (or the reverse), a row
whose Platform names a different fetcher category than the fetcher's own,
duplicate rows. Problems never stop the import; they are printed, and with
--report written as Markdown for the refresh PR's body
(.github/workflows/solcap-mapping-refresh.yml).

Usage:
  python tools/import_solcap_mapping.py path/to/20x-mapping.csv [--out FILE] [--check] [--report FILE]

--check exits 1 when the file on disk differs from what the CSV would produce,
without writing.
"""

import argparse
import csv
import json
import re
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, List, Optional

import yaml
from jsonschema import Draft202012Validator

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from framework.config_loader import discover_fetchers  # noqa: E402

HEADER = """\
# Which solution capabilities each fetcher's evidence speaks to.
#
# GENERATED by tools/import_solcap_mapping.py from the "Fetcher to Sol Cap
# Mapping" sheet ("20x Mapping" tab), refreshed weekly by
# .github/workflows/solcap-mapping-refresh.yml. Edit the sheet and re-import; a
# hand edit here is lost on the next import.
#
# A SUGGESTION list for whoever authors a validator for a fetcher's evidence
# set: the capabilities that validator could prove. Nothing reads it to pair or
# attach anything on its own.
# `id` is the library capability id (RS-02-03-01); `name` is offered for name
# matching in workspaces whose capabilities carry no ids. Program controls never
# appear here: a capability maps to controls per program, inside Paramify.
"""

COLUMNS = {"id": "Sol Cap ID", "name": "Sol Cap", "ksi": "KSI", "fetcher": "Fetcher Name"}
PLATFORM_COLUMN = "Platform"
LIBRARY_ID = re.compile(r"RS-\d{2}-\d{2}-\d{2}")
MAPPING_PATH = Path("mappings") / "solution_capabilities.yaml"
SCHEMA_PATH = REPO_ROOT / "framework" / "schemas" / "solcap_mapping_schema.json"

#: Problem kinds, in report order, with the heading each gets.
KINDS = {
    "bad_id": "Not a library id",
    "id_names": "One id, several names",
    "name_ids": "One name, several ids",
    "platform": "Platform disagrees with the fetcher",
    "unknown_fetcher": "Fetcher not in this repo (rows left out)",
    "missing_id": "No Sol Cap ID (name match only)",
    "duplicate": "Duplicate rows",
}


def _clean(value) -> str:
    # The sheet escapes underscores in some exports (aws\_backup\_validation).
    return (value or "").replace("\\_", "_").strip()


def _squash(value: str) -> str:
    """Platform text compared loosely: "Better Stack" == "betterstack"."""
    return re.sub(r"[^a-z0-9]", "", value.lower())


def _row(row) -> Dict[str, str]:
    return {k: _clean(row.get(col)) for k, col in COLUMNS.items()}


def build(rows, imported_at: str, known_fetchers=None) -> dict:
    """Collapse sheet rows into the mapping document. With `known_fetchers`,
    rows naming any other fetcher are left out."""
    grouped = {}
    for raw in rows:
        r = _row(raw)
        if not r["fetcher"] or not r["name"]:
            continue
        if known_fetchers is not None and r["fetcher"] not in known_fetchers:
            continue
        entry = grouped.setdefault((r["fetcher"], r["id"], r["name"]), set())
        if r["ksi"]:
            entry.add(r["ksi"])

    mappings = []
    for (fetcher, cap_id, name), ksis in sorted(grouped.items(), key=lambda kv: (kv[0][0], kv[0][2].lower(), kv[0][1])):
        cap = {"id": cap_id, "name": name} if cap_id else {"name": name}
        m = {"fetcher": fetcher, "solution_capability": cap}
        if ksis:
            m["ksis"] = sorted(ksis)
        mappings.append(m)
    return {
        "source": {
            "sheet": "Fetcher to Sol Cap Mapping",
            "tab": "20x Mapping",
            "imported_at": imported_at,
        },
        "mappings": mappings,
    }


# --------------------------------------------------------------------------- #
# Checks
# --------------------------------------------------------------------------- #
@dataclass
class Problem:
    kind: str
    detail: str
    #: Sheet row numbers (the header is row 1).
    rows: List[int] = field(default_factory=list)


def check(rows, fetchers: dict) -> List[Problem]:
    """What looks wrong in the sheet rows that would be imported.

    `fetchers` is {name: Fetcher}. Rows with no fetcher or no name are not
    checked: the import skips them anyway. Row numbers assume `rows` holds every
    sheet row in order, blank ones included.
    """
    found: Dict[tuple, Problem] = {}

    def add(kind: str, detail: str, row_no: int) -> None:
        found.setdefault((kind, detail), Problem(kind, detail)).rows.append(row_no)

    categories = {_squash(f.category): f.category for f in fetchers.values() if f.category}
    names_by_id: Dict[str, Dict[str, List[int]]] = defaultdict(lambda: defaultdict(list))
    ids_by_name: Dict[str, Dict[str, List[int]]] = defaultdict(lambda: defaultdict(list))
    seen: Dict[tuple, int] = {}

    for i, raw in enumerate(rows):
        row_no = i + 2
        r = _row(raw)
        if not r["fetcher"] or not r["name"]:
            continue
        fetcher = fetchers.get(r["fetcher"])
        if fetcher is None:
            add("unknown_fetcher", f"`{r['fetcher']}`", row_no)
        if not r["id"]:
            add("missing_id", r["name"], row_no)
        elif not LIBRARY_ID.fullmatch(r["id"]):
            add("bad_id", f"`{r['id']}` ({r['name']})", row_no)
        if r["id"]:
            names_by_id[r["id"]][r["name"]].append(row_no)
            ids_by_name[r["name"]][r["id"]].append(row_no)

        # The Platform column is free text ("Gitlab", "S3", "AWS IAM"), so only
        # flag a value that names a DIFFERENT fetcher category outright.
        platform_text = _clean(raw.get(PLATFORM_COLUMN))
        platform = _squash(platform_text)
        if fetcher is not None and fetcher.category and platform in categories \
                and categories[platform] != fetcher.category:
            add("platform",
                f"`{r['fetcher']}` is a {fetcher.category} fetcher; the row says {platform_text}",
                row_no)

        key = (r["fetcher"], r["id"], r["name"], r["ksi"])
        if key in seen:
            add("duplicate", f"`{r['fetcher']}` × {r['id'] or r['name']} × {r['ksi'] or 'no KSI'}"
                f" (first at row {seen[key]})", row_no)
        else:
            seen[key] = row_no

    for cap_id, names in names_by_id.items():
        if len(names) > 1:
            detail = f"`{cap_id}`: " + " / ".join(sorted(names))
            for row_nos in names.values():
                for n in row_nos:
                    add("id_names", detail, n)
    for name, ids in ids_by_name.items():
        if len(ids) > 1:
            detail = f"{name}: " + ", ".join(f"`{x}`" for x in sorted(ids))
            for row_nos in ids.values():
                for n in row_nos:
                    add("name_ids", detail, n)

    order = list(KINDS)
    for p in found.values():
        p.rows.sort()
    return sorted(found.values(), key=lambda p: (order.index(p.kind), p.detail.lower()))


# --------------------------------------------------------------------------- #
# What changed
# --------------------------------------------------------------------------- #
def _mapping_key(m: dict) -> tuple:
    cap = m["solution_capability"]
    return (m["fetcher"], cap.get("id") or "", cap["name"])


def _label(key: tuple) -> str:
    fetcher, cap_id, name = key
    return f"`{fetcher}` → {cap_id + ' ' if cap_id else ''}{name}"


def diff(old: Optional[dict], new: dict) -> dict:
    """Mappings added, removed, and whose KSIs moved, between two documents."""
    before = {_mapping_key(m): sorted(m.get("ksis") or []) for m in (old or {}).get("mappings") or []}
    after = {_mapping_key(m): sorted(m.get("ksis") or []) for m in new.get("mappings") or []}
    return {
        "added": sorted(after.keys() - before.keys()),
        "removed": sorted(before.keys() - after.keys()),
        "ksis": sorted(k for k in after.keys() & before.keys() if after[k] != before[k]),
    }


# --------------------------------------------------------------------------- #
# Report
# --------------------------------------------------------------------------- #
def _ranges(numbers: List[int]) -> str:
    """[3, 4, 5, 9] -> "3–5, 9"."""
    spans: List[List[int]] = []
    for n in sorted(set(numbers)):
        if spans and n == spans[-1][1] + 1:
            spans[-1][1] = n
        else:
            spans.append([n, n])
    return ", ".join(str(a) if a == b else f"{a}–{b}" for a, b in spans)


def _details(title: str, lines: List[str], limit: int = 200) -> List[str]:
    if not lines:
        return []
    shown = lines[:limit] + ([f"- … and {len(lines) - limit} more"] if len(lines) > limit else [])
    return ["<details>", f"<summary>{title} ({len(lines)})</summary>", "", *shown, "", "</details>", ""]


def report(doc: dict, changes: dict, problems: List[Problem], row_count: int) -> str:
    """Markdown for the refresh PR body."""
    mappings = doc["mappings"]
    no_id = sum(1 for m in mappings if "id" not in m["solution_capability"])
    lines = [
        "## Solution capability mapping refresh",
        "",
        f"Regenerated `{MAPPING_PATH}` from the \"20x Mapping\" tab on "
        f"{doc['source']['imported_at']}: {row_count} sheet rows → {len(mappings)} mappings "
        f"({no_id} without an id).",
        "",
        "### Changes",
        "",
    ]
    if any(changes.values()):
        lines += [
            f"{len(changes['added'])} added, {len(changes['removed'])} removed, "
            f"{len(changes['ksis'])} with different KSIs.",
            "",
        ]
        lines += _details("Added", [f"- {_label(k)}" for k in changes["added"]])
        lines += _details("Removed", [f"- {_label(k)}" for k in changes["removed"]])
        lines += _details("KSIs changed", [f"- {_label(k)}" for k in changes["ksis"]])
    else:
        lines += ["No mapping changed.", ""]

    lines += ["### Sheet problems", ""]
    if not problems:
        lines += ["None found.", ""]
    else:
        lines += [
            "Fix these in the sheet; the next refresh picks the fix up. None of them "
            "stopped this import.",
            "",
        ]
        by_kind: Dict[str, List[Problem]] = defaultdict(list)
        for p in problems:
            by_kind[p.kind].append(p)
        for kind, heading in KINDS.items():
            if kind not in by_kind:
                continue
            lines += [f"**{heading}**", "", "| | Sheet rows |", "|---|---|"]
            lines += [f"| {p.detail} | {_ranges(p.rows)} |" for p in by_kind[kind]]
            lines.append("")
    lines += [
        "---",
        "Opened by `.github/workflows/solcap-mapping-refresh.yml`. The mapping only suggests "
        "capabilities while a validator is authored; merging this pairs nothing.",
    ]
    return "\n".join(lines) + "\n"


def render(doc: dict) -> str:
    return HEADER + "\n" + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=100)


def _body(text: str) -> str:
    """The file minus its import timestamp, for change detection."""
    return "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("imported_at:"))


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("csv", help="CSV export of the sheet's 20x Mapping tab")
    parser.add_argument("--out", default=str(REPO_ROOT / MAPPING_PATH), help="Output YAML (default mappings/solution_capabilities.yaml)")
    parser.add_argument("--check", action="store_true", help="Exit 1 if the output would change; write nothing")
    parser.add_argument("--report", metavar="FILE", help="Also write a Markdown summary (changes + sheet problems)")
    args = parser.parse_args(argv)

    with open(args.csv, newline="", encoding="utf-8-sig") as fh:
        reader = csv.DictReader(fh)
        missing = [c for c in COLUMNS.values() if c not in (reader.fieldnames or [])]
        if missing:
            print(f"error: CSV is missing column(s): {', '.join(missing)}", file=sys.stderr)
            return 2
        rows = list(reader)

    fetchers = discover_fetchers(REPO_ROOT)
    doc = build(rows, datetime.now(timezone.utc).strftime("%Y-%m-%d"), known_fetchers=fetchers)
    errors = list(Draft202012Validator(json.loads(SCHEMA_PATH.read_text())).iter_errors(doc))
    if errors:
        print("error: the import does not match the mapping schema:", file=sys.stderr)
        for e in errors[:10]:
            print(f"  {e.message}", file=sys.stderr)
        return 2
    text = render(doc)
    out = Path(args.out)
    current = out.read_text() if out.is_file() else ""
    problems = check(rows, fetchers)
    changes = diff(yaml.safe_load(current) if current else None, doc)

    no_id = sum(1 for m in doc["mappings"] if "id" not in m["solution_capability"])
    print(
        f"{len(rows)} sheet rows -> {len(doc['mappings'])} mapping(s), "
        f"{no_id} without an id (name match, needs approval)",
        file=sys.stderr,
    )
    print(f"{len(changes['added'])} added, {len(changes['removed'])} removed, "
          f"{len(changes['ksis'])} with different KSIs", file=sys.stderr)
    for p in problems:
        print(f"warning: {KINDS[p.kind]}: {p.detail} (sheet rows {_ranges(p.rows)})", file=sys.stderr)
    if args.report:
        Path(args.report).write_text(report(doc, changes, problems, len(rows)))

    changed = _body(current) != _body(text)
    if args.check:
        print("changed" if changed else "unchanged", file=sys.stderr)
        return 1 if changed else 0
    if not changed:
        print(f"{out}: unchanged", file=sys.stderr)
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"wrote {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
